-- Secuencia de guias: ultima guia 'EE' + 13 digitos cargada + 1 (calculado)
DECLARE
    v_ultima NUMBER;
BEGIN
    SELECT NVL(MAX(TO_NUMBER(SUBSTR(numero_guia, 3))), 0)
    INTO   v_ultima
    FROM   envio
    WHERE  REGEXP_LIKE(numero_guia, '^EE[0-9]{13}$');
    EXECUTE IMMEDIATE 'ALTER SEQUENCE seq_numero_guia RESTART START WITH ' || (v_ultima + 1);
    DBMS_OUTPUT.PUT_LINE('seq_numero_guia reiniciada en ' || (v_ultima + 1));
END;
