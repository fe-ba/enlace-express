-- Extension E1: usuarios de la aplicacion y codigos de activacion (decisiones 12.3 y 12.5).
-- Fuera del modulo M1: las 19 tablas del modulo no se tocan. Se ejecuta como
-- BD_ENLACE_EXPRESS, despues de seed. Estas tablas no se conceden a ningun
-- rol: solo se accede a ellas por los paquetes pkg_seguridad y
-- pkg_codigos_activacion.
WHENEVER SQLERROR EXIT FAILURE
SET DEFINE OFF
ALTER SESSION SET NLS_LENGTH_SEMANTICS = CHAR;

CREATE TABLE usuario_aplicacion (
    id_usuario      NUMBER (10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_usuario  VARCHAR2 (60) NOT NULL,
    hash_contrasena VARCHAR2 (100) NOT NULL,
    rol             VARCHAR2 (12) NOT NULL,
    id_empleado     NUMBER (10),
    id_cliente      NUMBER (10),
    estado          VARCHAR2 (10) DEFAULT 'ACTIVO' NOT NULL,
    fecha_creacion  TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    ultimo_ingreso  TIMESTAMP
)
TABLESPACE TS_ENLACE_DATOS
LOGGING;

ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_rol_ck
    CHECK (rol IN ('GERENCIA', 'CENTRO', 'MESA', 'MENSAJERO', 'CLIENTE'));
ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_estado_ck
    CHECK (estado IN ('ACTIVO', 'INACTIVO'));
-- el cliente se vincula a una empresa; el resto de roles a un empleado
ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_vinculo_ck
    CHECK ((rol = 'CLIENTE' AND id_cliente IS NOT NULL AND id_empleado IS NULL)
        OR (rol <> 'CLIENTE' AND id_empleado IS NOT NULL AND id_cliente IS NULL));

COMMENT ON TABLE usuario_aplicacion IS 'Extensión E1: cuenta de acceso a la aplicación, con su rol y su vínculo con un empleado o un cliente.';
COMMENT ON COLUMN usuario_aplicacion.id_usuario IS 'Identificador de la cuenta';
COMMENT ON COLUMN usuario_aplicacion.nombre_usuario IS 'Nombre de usuario para iniciar sesión (único)';
COMMENT ON COLUMN usuario_aplicacion.hash_contrasena IS 'Hash BCrypt de la contraseña; lo calcula la aplicación, la base nunca ve la contraseña';
COMMENT ON COLUMN usuario_aplicacion.rol IS 'GERENCIA, CENTRO, MESA, MENSAJERO o CLIENTE; se deriva del cargo del empleado';
COMMENT ON COLUMN usuario_aplicacion.id_empleado IS 'Empleado dueño de la cuenta (roles internos); una cuenta por empleado';
COMMENT ON COLUMN usuario_aplicacion.id_cliente IS 'Empresa cliente de la cuenta (rol CLIENTE); una empresa puede tener varias cuentas';
COMMENT ON COLUMN usuario_aplicacion.estado IS 'ACTIVO o INACTIVO; por defecto ACTIVO';
COMMENT ON COLUMN usuario_aplicacion.fecha_creacion IS 'Instante en que se registró la cuenta';
COMMENT ON COLUMN usuario_aplicacion.ultimo_ingreso IS 'Instante del último inicio de sesión correcto';

ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_pk PRIMARY KEY (id_usuario)
    USING INDEX TABLESPACE TS_ENLACE_INDICES;
ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_nombre_uk UNIQUE (nombre_usuario)
    USING INDEX TABLESPACE TS_ENLACE_INDICES;
ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_empleado_uk UNIQUE (id_empleado)
    USING INDEX TABLESPACE TS_ENLACE_INDICES;
ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_empleado_fk FOREIGN KEY (id_empleado)
    REFERENCES empleado (id_empleado);
ALTER TABLE usuario_aplicacion ADD CONSTRAINT usuario_cliente_fk FOREIGN KEY (id_cliente)
    REFERENCES cliente (id_cliente);

CREATE TABLE codigo_activacion (
    id_codigo         NUMBER (10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo_hash       VARCHAR2 (64) NOT NULL,
    id_empleado       NUMBER (10),
    id_cliente        NUMBER (10),
    fecha_generacion  TIMESTAMP NOT NULL,
    fecha_vencimiento TIMESTAMP NOT NULL,
    fecha_uso         TIMESTAMP,
    id_usuario        NUMBER (10)
)
TABLESPACE TS_ENLACE_DATOS
LOGGING;

-- el codigo es para un empleado o para un cliente, nunca para ambos ni para ninguno
ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_destino_ck
    CHECK ((id_empleado IS NOT NULL AND id_cliente IS NULL) OR (id_empleado IS NULL AND id_cliente IS NOT NULL));
ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_vigencia_ck
    CHECK (fecha_vencimiento > fecha_generacion);
-- un codigo usado dice cuando y quien; uno sin usar no tiene ni fecha ni usuario
ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_uso_ck
    CHECK ((fecha_uso IS NULL AND id_usuario IS NULL) OR (fecha_uso IS NOT NULL AND id_usuario IS NOT NULL));

COMMENT ON TABLE codigo_activacion IS 'Extensión E1: código de activación de un solo uso y con vencimiento para registrar a un empleado o a un cliente.';
COMMENT ON COLUMN codigo_activacion.id_codigo IS 'Identificador del código';
COMMENT ON COLUMN codigo_activacion.codigo_hash IS 'SHA-256 en hexadecimal del código; el código en claro solo se muestra una vez, al generarlo';
COMMENT ON COLUMN codigo_activacion.id_empleado IS 'Empleado al que se le entrega el código (excluyente con id_cliente)';
COMMENT ON COLUMN codigo_activacion.id_cliente IS 'Cliente al que se le entrega el código (excluyente con id_empleado)';
COMMENT ON COLUMN codigo_activacion.fecha_generacion IS 'Instante en que el administrador generó el código';
COMMENT ON COLUMN codigo_activacion.fecha_vencimiento IS 'Instante a partir del cual el código ya no sirve';
COMMENT ON COLUMN codigo_activacion.fecha_uso IS 'Instante en que se usó para registrarse; nulo mientras no se use';
COMMENT ON COLUMN codigo_activacion.id_usuario IS 'Cuenta que se creó con el código; nulo mientras no se use';

ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_pk PRIMARY KEY (id_codigo)
    USING INDEX TABLESPACE TS_ENLACE_INDICES;
ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_hash_uk UNIQUE (codigo_hash)
    USING INDEX TABLESPACE TS_ENLACE_INDICES;
ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_empleado_fk FOREIGN KEY (id_empleado)
    REFERENCES empleado (id_empleado);
ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_cliente_fk FOREIGN KEY (id_cliente)
    REFERENCES cliente (id_cliente);
ALTER TABLE codigo_activacion ADD CONSTRAINT codigo_usuario_fk FOREIGN KEY (id_usuario)
    REFERENCES usuario_aplicacion (id_usuario);

-- indices sobre las claves foraneas no cubiertas por otro indice
CREATE INDEX usuario_cliente_fk_ix ON usuario_aplicacion (id_cliente) TABLESPACE TS_ENLACE_INDICES;
CREATE INDEX codigo_empleado_fk_ix ON codigo_activacion (id_empleado) TABLESPACE TS_ENLACE_INDICES;
CREATE INDEX codigo_cliente_fk_ix ON codigo_activacion (id_cliente) TABLESPACE TS_ENLACE_INDICES;
CREATE INDEX codigo_usuario_fk_ix ON codigo_activacion (id_usuario) TABLESPACE TS_ENLACE_INDICES;
